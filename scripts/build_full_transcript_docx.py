"""연신내지역주택조합 면담 전체 녹취록(축자기록·전문) docx 생성."""

from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement


FONT = "맑은 고딕"
MONO = "Consolas"


def kfont(run, *, name=FONT, size=10, bold=False, color=None, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:eastAsia"), name)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)


def para(doc, text, *, size=10, bold=False, align=None,
         color=None, space_after=2, indent=None):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    if indent is not None:
        p.paragraph_format.left_indent = Cm(indent)
    r = p.add_run(text)
    kfont(r, size=size, bold=bold, color=color)
    return p


def hr(doc):
    p = doc.add_paragraph()
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "808080")
    pBdr.append(bottom)
    pPr.append(pBdr)


def dialogue(doc, time, speaker, content):
    """시간코드 / 화자 / 내용 한 줄."""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.left_indent = Cm(2.0)
    p.paragraph_format.first_line_indent = Cm(-2.0)

    r_time = p.add_run(f"[{time}] ")
    kfont(r_time, name=MONO, size=9, bold=True,
          color=RGBColor(0x55, 0x55, 0x55))

    is_gap = speaker == "갑"
    color = RGBColor(0xC0, 0x00, 0x00) if is_gap else RGBColor(0x00, 0x33, 0x66)
    r_speaker = p.add_run(f"{speaker} : ")
    kfont(r_speaker, size=10, bold=True, color=color)

    r_content = p.add_run(content)
    kfont(r_content, size=10)


